// Command gen writes the methods that make Client and Switch each a Host, from
// the interfaces in backend.go. Run it with go generate in internal/remote
// after changing them; a test fails when the files are stale.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

func main() {
	dir := "."
	if len(os.Args) > 1 {
		dir = os.Args[1]
	}
	src, err := os.ReadFile(filepath.Join(dir, "backend.go"))
	if err != nil {
		log.Fatal(err)
	}
	files, err := generate(src)
	if err != nil {
		log.Fatal(err)
	}
	for name, data := range files {
		if err := os.WriteFile(filepath.Join(dir, name), data, 0o644); err != nil {
			log.Fatal(err)
		}
	}
}

type param struct{ name, typ string }

type method struct {
	name    string
	params  []param
	results []string // types, the trailing error included
}

func (m method) hasErr() bool {
	return len(m.results) > 0 && m.results[len(m.results)-1] == "error"
}

// values are the results other than a trailing error.
func (m method) values() []string {
	if m.hasErr() {
		return m.results[:len(m.results)-1]
	}
	return m.results
}

// generate returns the generated files by name.
func generate(src []byte) (map[string][]byte, error) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, "backend.go", src, 0)
	if err != nil {
		return nil, err
	}
	ifaces := map[string]*ast.InterfaceType{}
	imports := map[string]string{} // package name -> path
	for _, imp := range f.Imports {
		path, _ := strconv.Unquote(imp.Path.Value)
		name := filepath.Base(path)
		if imp.Name != nil {
			name = imp.Name.Name
		}
		imports[name] = path
	}
	ast.Inspect(f, func(n ast.Node) bool {
		if ts, ok := n.(*ast.TypeSpec); ok {
			if it, ok := ts.Type.(*ast.InterfaceType); ok {
				ifaces[ts.Name.Name] = it
			}
		}
		return true
	})

	var collect func(name string) ([]method, error)
	collect = func(name string) ([]method, error) {
		it, ok := ifaces[name]
		if !ok {
			return nil, fmt.Errorf("interface %s not found", name)
		}
		var out []method
		for _, field := range it.Methods.List {
			switch t := field.Type.(type) {
			case *ast.Ident: // an embedded interface
				embedded, err := collect(t.Name)
				if err != nil {
					return nil, err
				}
				out = append(out, embedded...)
			case *ast.FuncType:
				m := method{name: field.Names[0].Name}
				n := 0
				for _, p := range t.Params.List {
					typ := exprString(fset, p.Type)
					if len(p.Names) == 0 {
						m.params = append(m.params, param{fmt.Sprintf("p%d", n), typ})
						n++
					}
					for _, id := range p.Names {
						m.params = append(m.params, param{id.Name, typ})
						n++
					}
				}
				if t.Results != nil {
					for _, r := range t.Results.List {
						typ := exprString(fset, r.Type)
						count := len(r.Names)
						if count == 0 {
							count = 1
						}
						for i := 0; i < count; i++ {
							m.results = append(m.results, typ)
						}
					}
				}
				out = append(out, m)
			default:
				return nil, fmt.Errorf("%s: unexpected member %T", name, t)
			}
		}
		return out, nil
	}

	host, err := collect("Host")
	if err != nil {
		return nil, err
	}

	var client, sw bytes.Buffer
	uses := map[string]bool{}
	for _, m := range host {
		writeClientMethod(&client, m)
		writeSwitchMethod(&sw, m)
		noteUses(uses, m, imports)
	}

	files := map[string][]byte{}
	for name, buf := range map[string]*bytes.Buffer{"client_gen.go": &client, "switch_gen.go": &sw} {
		var out bytes.Buffer
		out.WriteString("// Code generated by internal/remote/gen from backend.go. DO NOT EDIT.\n\npackage remote\n\n")
		if len(uses) > 0 {
			var paths []string
			for pkg := range uses {
				paths = append(paths, imports[pkg])
			}
			sort.Strings(paths)
			out.WriteString("import (\n")
			for _, p := range paths {
				fmt.Fprintf(&out, "\t%q\n", p)
			}
			out.WriteString(")\n\n")
		}
		out.Write(buf.Bytes())
		formatted, err := format.Source(out.Bytes())
		if err != nil {
			return nil, fmt.Errorf("%s: %w\n%s", name, err, out.String())
		}
		files[name] = formatted
	}
	return files, nil
}

func exprString(fset *token.FileSet, e ast.Expr) string {
	var b bytes.Buffer
	_ = printer.Fprint(&b, fset, e)
	return b.String()
}

// noteUses records which imported packages a method's types refer to.
func noteUses(uses map[string]bool, m method, imports map[string]string) {
	types := append([]string{}, m.results...)
	for _, p := range m.params {
		types = append(types, p.typ)
	}
	for _, t := range types {
		for pkg := range imports {
			if strings.Contains(t, pkg+".") {
				uses[pkg] = true
			}
		}
	}
}

func signature(m method) string {
	var ps []string
	for _, p := range m.params {
		ps = append(ps, p.name+" "+p.typ)
	}
	res := ""
	switch len(m.results) {
	case 0:
	case 1:
		res = " " + m.results[0]
	default:
		res = " (" + strings.Join(m.results, ", ") + ")"
	}
	return fmt.Sprintf("%s(%s)%s", m.name, strings.Join(ps, ", "), res)
}

func argList(m method) string {
	var names []string
	for _, p := range m.params {
		names = append(names, p.name)
	}
	return strings.Join(names, ", ")
}

func writeClientMethod(b *bytes.Buffer, m method) {
	fmt.Fprintf(b, "func (c *Client) %s {\n", signature(m))
	values := m.values()
	var ptrs, rets []string
	for i, t := range values {
		fmt.Fprintf(b, "\tvar r%d %s\n", i, t)
		ptrs = append(ptrs, fmt.Sprintf("&r%d", i))
		rets = append(rets, fmt.Sprintf("r%d", i))
	}
	callArgs := fmt.Sprintf("%q, []any{%s}", m.name, argList(m))
	if len(ptrs) > 0 {
		callArgs += ", " + strings.Join(ptrs, ", ")
	}
	if m.hasErr() {
		fmt.Fprintf(b, "\terr := c.call(%s)\n", callArgs)
		rets = append(rets, "err")
	} else {
		fmt.Fprintf(b, "\tc.logLost(%q, c.call(%s))\n", m.name, callArgs)
	}
	if len(rets) > 0 {
		fmt.Fprintf(b, "\treturn %s\n", strings.Join(rets, ", "))
	}
	b.WriteString("}\n\n")
}

func writeSwitchMethod(b *bytes.Buffer, m method) {
	fmt.Fprintf(b, "func (s *Switch) %s {\n", signature(m))
	call := fmt.Sprintf("s.Current().%s(%s)", m.name, argList(m))
	if len(m.results) > 0 {
		fmt.Fprintf(b, "\treturn %s\n", call)
	} else {
		fmt.Fprintf(b, "\t%s\n", call)
	}
	b.WriteString("}\n\n")
}
